// @ts-check
const { test, expect } = require('@playwright/test');
const { observe, fixture, environment, runs } = require('./helpers');

test.describe.configure({ mode: 'serial' });

let plugins = [];

test.beforeAll(async () => {
	plugins = (await environment()).plugins;
});

test.beforeEach(async ({ context }) => {
	await context.clearCookies();
});

const pages = () => [
	['/', true],
	['/shop/', plugins.includes('woocommerce')],
	['/product/e2e-product/', plugins.includes('woocommerce')],
	['/elementor-page/', plugins.includes('elementor')],
	['/de/', plugins.includes('polylang')],
].filter(([, enabled]) => enabled).map(([path]) => path);

test('every page type: nothing before consent, everything allowed after, nothing after rejecting', async ({ browser }) => {
	test.skip(0 === plugins.filter((p) => 'consentimental' !== p).length, 'No third-party plugins active (run bin/e2e-env.sh compat ...)');

	for (const path of pages()) {
		await test.step(path, async () => {
			const accepting = await browser.newContext();
			const net = await observe(accepting);
			const page = await accepting.newPage();
			await page.goto(path);
			await expect(page.locator('#cmp-banner'), path).toBeVisible();
			await page.waitForLoadState('networkidle');
			expect(net.hosts(), `${path} before consent`).toEqual([]);

			await page.locator('#cmp-banner [data-cmp-action="accept-all"]').click();
			await expect.poll(() => runs(page), path).toMatchObject({ analytics: 1, ads: 1 });
			if ('/elementor-page/' === path) {
				await expect(page.locator('#cmp-e2e-elementor-video')).toHaveAttribute('src', /embed\/elementor/);
			}
			await page.reload();
			await expect(page.locator('#cmp-banner')).toBeHidden();
			await expect.poll(() => runs(page), `${path} after reload`).toMatchObject({ analytics: 1, ads: 1 });
			await accepting.close();

			const rejecting = await browser.newContext();
			const rejected = await observe(rejecting);
			const other = await rejecting.newPage();
			await other.goto(path);
			await other.locator('#cmp-banner [data-cmp-action="reject-all"]').click();
			await other.reload();
			await other.waitForLoadState('networkidle');
			expect(rejected.hosts(), `${path} after rejecting`).toEqual([]);
			await rejecting.close();
		});
	}
});

test('Autoptimize: aggregated scripts do not break release or blocking', async ({ page, context }) => {
	test.skip(!plugins.includes('autoptimize'), 'Autoptimize not active');
	await observe(context);
	await page.goto('/');
	await expect(page.locator('script[src*="/cache/autoptimize/"]').first()).toBeAttached();
	expect(await page.evaluate(() => document.getElementById('cmp-bootstrap') !== null && typeof window.CMP)).toBe('object');
	await expect(page.locator('script[src*="cmp-e2e.test"][type="text/plain"]')).toHaveCount(3);
});

test('WP Super Cache: cached pages still enforce consent, publishing purges the cache', async ({ request, page, context }) => {
	test.skip(!plugins.includes('wp-super-cache'), 'WP Super Cache not active');
	const html = async () => (await request.get('/about/', { headers: { cookie: '' } })).text();
	const stamp = (body) => (body.match(/Cached page generated by WP-Super-Cache on ([\d: -]+?) -->/) || [])[1];
	await expect.poll(async () => {
		const first = stamp(await html());
		return !!first && first === stamp(await html());
	}, { message: 'two consecutive anonymous requests are served from the cache' }).toBe(true);

	const version = await fixture({ bump: true });
	expect(await html()).toContain(`"configVersion":${version}`);

	const net = await observe(context);
	await html();
	await page.goto('/about/');
	await page.waitForLoadState('networkidle');
	expect(net.hosts()).toEqual([]);
	await expect(page.locator('#cmp-banner')).toBeVisible();
});

test('Polylang: each language gets its own disclosure snapshot and translated wording', async ({ browser }) => {
	test.skip(!plugins.includes('polylang'), 'Polylang not active');
	await fixture({ banner_title: 'Your privacy choices' });
	const context = await browser.newContext();
	await observe(context);
	const page = await context.newPage();

	await page.goto('/');
	const english = await page.evaluate(() => window.cmpConfig.disclosure);
	await expect(page.locator('#cmp-banner-title')).toHaveText('Your privacy choices');

	await page.goto('/de/');
	const german = await page.evaluate(() => window.cmpConfig.disclosure);
	await expect(page.locator('#cmp-banner-title')).toHaveText('Ihre Datenschutz-Einstellungen');

	expect(english.language.code).toBe('en');
	expect(german.language).toMatchObject({ code: 'de', locale: 'de_DE' });
	expect(german.id).not.toBe(english.id);

	const recorded = page.waitForResponse((r) => r.url().includes('/consentimental/v1/consent') && 'POST' === r.request().method());
	await page.locator('#cmp-banner [data-cmp-action="reject-all"]').click();
	const response = await recorded;
	expect(response.status()).toBe(200);
	expect(JSON.parse(response.request().postData() || '{}').disclosure_id).toBe(german.id);
	await context.close();
	await fixture({ banner_title: '' });
});
